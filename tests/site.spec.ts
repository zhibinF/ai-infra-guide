import {test,expect} from '@playwright/test'
import fs from 'node:fs'
test('source data and search, filters, empty state',async({page})=>{
 await page.goto('./#/resources')
 await expect(page.getByText('找到 72 条推荐资料')).toBeVisible()
 await page.getByLabel('搜索资料标题').fill('flashattention')
 await expect(page.locator('.resource')).not.toHaveCount(0)
 await expect(page.locator('.resource').first()).toContainText(/FlashAttention/i)
 await page.getByLabel('主题筛选').selectOption('c3')
 await expect(page.locator('.empty')).toBeVisible()
 await page.getByLabel('搜索资料标题').fill('')
 await expect(page.locator('.resource')).toHaveCount(9)
 await expect(page.locator('.resource').first()).toContainText('对应链接待核对')
 await expect(page.locator('.resource').first().locator('.origin')).toHaveAttribute('href',/mp.weixin.qq.com/)
})
test('progress persists, exports and imports atomically',async({page})=>{
 await page.goto('./#/progress')
 const first=page.locator('.resource select').first()
 await first.selectOption('learning');await page.reload();await expect(first).toHaveValue('learning')
 const download=page.waitForEvent('download');await page.getByRole('button',{name:'导出进度 JSON'}).click()
 const file=await(await download).path();expect(JSON.parse(fs.readFileSync(file!,'utf8')).progress.r1).toBe('learning')
 await page.getByLabel('导入进度 JSON').setInputFiles({name:'valid.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify({version:1,progress:{r1:'done'}}))})
 await expect(first).toHaveValue('done');await page.reload();await expect(first).toHaveValue('done')
 await page.getByLabel('导入进度 JSON').setInputFiles({name:'bad.json',mimeType:'application/json',buffer:Buffer.from('{"version":1,"progress":{"r1":"oops"}}')})
 await expect(page.getByRole('status')).toContainText('导入失败');await expect(first).toHaveValue('done')
 await page.getByLabel('进度筛选').selectOption('done');await expect(page.locator('.resource')).toHaveCount(1)
})
